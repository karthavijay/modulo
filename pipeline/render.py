"""Turn the agents' JSON into readable Markdown and a Word storyboard."""

from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor, Cm

BRAND = RGBColor(0x2F, 0x3E, 0x9E)


# ---------------------------------------------------------------- Markdown

def render_design_md(d: dict) -> str:
    lines = [f"# Course design: {d['title']}", "", d["summary"], "",
             f"- **Audience:** {d['audience']}",
             f"- **Business goal:** {d['business_goal']}",
             f"- **Seat time:** about {d['seat_time_minutes']:g} minutes",
             f"- **Approach:** {d['approach']}", "", "## Learning objectives", ""]
    lines += [f"- **{o['id']}** {o['text']} _({o['bloom_level']})_" for o in d["objectives"]]
    lines += ["", "## Modules", ""]
    for m in d["modules"]:
        lines += [f"### {m['id']}. {m['title']} ({m['duration_minutes']:g} min)",
                  f"Objectives: {', '.join(m['objective_ids'])}", "", "Topics:"]
        lines += [f"- {t}" for t in m["topics"]]
        lines += ["", "Interactions:"] + [f"- {i}" for i in m["interactions"]] + [""]
    a = d["assessment"]
    lines += ["## Assessment", "", a["description"], "",
              f"Items: {a['item_count']:g}. Pass mark: {a['pass_mark'].rstrip('.')}.", ""]
    for title, key in (("Delivery and accessibility", "delivery_notes"),
                       ("Assumptions", "assumptions"), ("Open questions for the client", "open_questions")):
        lines += [f"## {title}", ""] + [f"- {x}" for x in d[key]] + [""]
    return "\n".join(lines)


def render_storyboard_md(d: dict, sb: dict) -> str:
    words = sum(len(s["narration"].split()) for s in sb["screens"])
    lines = [f"# Storyboard: {sb['course_title']}", "",
             f"{len(sb['screens'])} screens, about {words} narration words "
             f"(roughly {words / 130:.0f} minutes of audio).", ""]
    for s in sb["screens"]:
        lines += [f"## {s['id']} {s['title']}", f"_{s['module']} | {s['screen_type']} | "
                  f"objectives: {', '.join(s['objective_ids']) or 'none'}_", "",
                  f"**On-screen text:** {s['on_screen_text']}", "",
                  f"**Narration:** {s['narration']}", "",
                  f"**Visuals:** {s['visuals']}", "",
                  f"**Interaction:** {s['interaction']}", "",
                  f"**Feedback:** {s['feedback']}", "",
                  f"**Notes:** {s['notes']}", ""]
    return "\n".join(lines)


def render_qa_md(rounds: list[dict]) -> str:
    lines = ["# QA report", ""]
    for i, qa in enumerate(rounds, 1):
        lines += [f"## Round {i}: {'PASS' if qa['pass'] else 'needs fixes'}", "", qa["summary"], "",
                  f"Estimated seat time: {qa['estimated_seat_time_minutes']:g} minutes", ""]
        if qa["findings"]:
            lines += ["| Severity | Screen | Issue | Fix |", "|---|---|---|---|"]
            for f in qa["findings"]:
                cells = [f["severity"], f["screen_id"], f["issue"], f["fix"]]
                lines.append("| " + " | ".join(c.replace("|", "/").replace("\n", " ") for c in cells) + " |")
            lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------- Word

def _shade(cell, hex_color: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tc_pr.append(shd)


def _widths(table, cms) -> None:
    table.autofit = False
    for col, w in zip(table._tbl.tblGrid.findall(qn("w:gridCol")), cms):
        col.set(qn("w:w"), str(int(w * 567)))  # twips
    for row in table.rows:
        for cell, w in zip(row.cells, cms):
            cell.width = Cm(w)


def _heading(doc, text: str, level: int) -> None:
    h = doc.add_heading(text, level=level)
    for r in h.runs:
        r.font.color.rgb = BRAND


def _bullets(doc, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def render_docx(d: dict, sb: dict, qa_rounds: list[dict], path: Path) -> None:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10.5)

    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Cm(1.8))
    sec.header.paragraphs[0].text = f"Modulo Learning Studio | Storyboard | {sb['course_title']}"
    sec.footer.paragraphs[0].text = "DRAFT for client and SME review. Generated by the Modulo agent pipeline."

    # Cover
    t = doc.add_paragraph()
    r = t.add_run(sb["course_title"])
    r.bold, r.font.size, r.font.color.rgb = True, Pt(26), BRAND
    doc.add_paragraph("Storyboard and course design").runs[0].font.size = Pt(14)
    final = qa_rounds[-1]
    words = sum(len(s["narration"].split()) for s in sb["screens"])
    info = doc.add_table(rows=0, cols=2)
    info.style = "Light Grid Accent 1"
    for k, v in (("Audience", d["audience"]), ("Business goal", d["business_goal"]),
                 ("Seat time", f"about {d['seat_time_minutes']:g} minutes (QA estimate "
                               f"{final['estimated_seat_time_minutes']:g})"),
                 ("Screens", f"{len(sb['screens'])} screens, {words} narration words"),
                 ("QA status", ("Passed" if final["pass"] else "Open findings remain")
                  + f" after {len(qa_rounds)} review round(s)"),
                 ("Approvals", "Course design approved by Modulo. Storyboard awaiting client and SME sign-off.")):
        row = info.add_row().cells
        row[0].text, row[1].text = k, v
        row[0].paragraphs[0].runs[0].bold = True
    doc.add_page_break()

    # Design
    _heading(doc, "1. Course design", 1)
    doc.add_paragraph(d["summary"])
    doc.add_paragraph().add_run("Approach: ").bold = True
    doc.paragraphs[-1].add_run(d["approach"])
    _heading(doc, "Learning objectives", 2)
    _bullets(doc, [f"{o['id']}  {o['text']} ({o['bloom_level']})" for o in d["objectives"]])
    _heading(doc, "Course map", 2)
    tbl = doc.add_table(rows=1, cols=4)
    tbl.style = "Light Grid Accent 1"
    for c, h in zip(tbl.rows[0].cells, ("Module", "Minutes", "Objectives", "Topics and interactions")):
        c.text = h
    for m in d["modules"]:
        c = tbl.add_row().cells
        c[0].text = f"{m['id']}. {m['title']}"
        c[1].text = f"{m['duration_minutes']:g}"
        c[2].text = ", ".join(m["objective_ids"])
        c[3].text = "; ".join(m["topics"]) + "\nInteractions: " + "; ".join(m["interactions"])
    _widths(tbl, (5.5, 1.8, 2.7, 15.5))
    _heading(doc, "Assessment", 2)
    doc.add_paragraph(f"{d['assessment']['description']} Items: {d['assessment']['item_count']:g}. "
                      f"Pass mark: {d['assessment']['pass_mark'].rstrip('.')}.")
    for title, key in (("Delivery and accessibility", "delivery_notes"), ("Assumptions", "assumptions"),
                       ("Open questions for the client", "open_questions")):
        _heading(doc, title, 2)
        _bullets(doc, d[key])
    doc.add_page_break()

    # Storyboard
    _heading(doc, "2. Storyboard", 1)
    fields = (("On-screen text", "on_screen_text"), ("Narration", "narration"), ("Visuals", "visuals"),
              ("Interaction", "interaction"), ("Feedback", "feedback"), ("Developer notes", "notes"))
    for s in sb["screens"]:
        table = doc.add_table(rows=1, cols=2)
        table.style = "Table Grid"
        head = table.rows[0].cells
        merged = head[0].merge(head[1])
        merged.text = ""
        run = merged.paragraphs[0].add_run(
            f"{s['id']}  {s['title']}    |    {s['module']}    |    {s['screen_type']}    |    "
            f"Objectives: {', '.join(s['objective_ids']) or 'none'}")
        run.bold, run.font.color.rgb = True, RGBColor(0xFF, 0xFF, 0xFF)
        _shade(merged, "2F3E9E")
        for label, key in fields:
            if not s[key].strip():
                continue
            c = table.add_row().cells
            c[0].text = label
            c[0].paragraphs[0].runs[0].bold = True
            _shade(c[0], "EEF0FA")
            c[1].text = s[key]
        _widths(table, (4, 21.5))
        doc.add_paragraph()

    # QA
    doc.add_page_break()
    _heading(doc, "3. QA review log", 1)
    for i, qa in enumerate(qa_rounds, 1):
        _heading(doc, f"Round {i}: {'Pass' if qa['pass'] else 'Needs fixes'}", 2)
        doc.add_paragraph(qa["summary"])
        if qa["findings"]:
            t = doc.add_table(rows=1, cols=4)
            t.style = "Light Grid Accent 1"
            for c, h in zip(t.rows[0].cells, ("Severity", "Screen", "Issue", "Fix")):
                c.text = h
            for f in qa["findings"]:
                c = t.add_row().cells
                c[0].text, c[1].text, c[2].text, c[3].text = f["severity"], f["screen_id"], f["issue"], f["fix"]
            _widths(t, (2, 3, 10.25, 10.25))
    doc.save(path)


# ---------------------------------------------------------------- production pack (the other agents' documents)

def _inline(par, text: str) -> None:
    """Add text to a paragraph, turning **bold** into bold runs."""
    import re as _re
    for i, part in enumerate(_re.split(r"\*\*(.+?)\*\*", text)):
        if part:
            par.add_run(part.replace("`", "")).bold = (i % 2 == 1)


def _md_to_docx(doc, md: str, base_level: int = 1) -> None:
    """Small Markdown converter: headings, bullets, numbered lists, pipe tables, paragraphs."""
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        s = line.strip()
        if not s:
            i += 1
            continue
        if s.startswith("#"):
            level = len(s) - len(s.lstrip("#"))
            _heading(doc, s.lstrip("#").strip().replace("**", ""), min(base_level + level - 1, 3))
        elif s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(set(c) <= set("-: ") for c in cells):
                    rows.append(cells)
                i += 1
            if rows:
                n = max(len(r) for r in rows)
                t = doc.add_table(rows=0, cols=n)
                t.style = "Light Grid Accent 1"
                for r in rows:
                    cells = t.add_row().cells
                    for c, v in zip(cells, r):
                        c.text = ""
                        _inline(c.paragraphs[0], v)
                doc.add_paragraph()
            continue
        elif s[:2] in ("- ", "* "):
            _inline(doc.add_paragraph(style="List Bullet"), s[2:])
        elif s.split(" ", 1)[0].rstrip(".").isdigit() and " " in s and s.split(" ", 1)[0].endswith("."):
            _inline(doc.add_paragraph(style="List Number"), s.split(" ", 1)[1])
        else:
            _inline(doc.add_paragraph(), s)
        i += 1


def render_pack_docx(course_title: str, docs: list[tuple[str, str]], path: Path) -> None:
    """docs: (agent heading, markdown document) in team order."""
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(10.5)
    sec = doc.sections[0]
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Cm(2))
    sec.header.paragraphs[0].text = f"Modulo Learning Studio | Production pack | {course_title}"
    sec.footer.paragraphs[0].text = "DRAFT for review. Generated by the Modulo agent team."
    t = doc.add_paragraph()
    r = t.add_run(course_title)
    r.bold, r.font.size, r.font.color.rgb = True, Pt(24), BRAND
    doc.add_paragraph("Production pack").runs[0].font.size = Pt(14)
    doc.add_paragraph("Contents:")
    for heading, _ in docs:
        doc.add_paragraph(heading, style="List Bullet")
    for heading, md in docs:
        doc.add_page_break()
        _heading(doc, heading, 1)
        _md_to_docx(doc, md, base_level=2)
    doc.save(path)
